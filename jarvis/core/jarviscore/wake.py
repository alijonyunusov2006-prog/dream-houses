"""Слово-активатор «Джарвис» и приветствия.

Окно JARVIS слушает микрофон, режет речь на фразы и присылает каждую на ПК; здесь решаем,
обращались ли к JARVIS. Зов — «Джарвис» в САМОМ НАЧАЛЕ фразы (можно с «эй» / «окей»):
имя в середине обычного разговора («мы обсуждали Джарвиса…») — не зов.
Распознавание путает имя, поэтому принимаем близкие написания.
"""

from __future__ import annotations

import re

_NAME = r"(?:джарвис|джарвиз|джервис|жарвис|джарвес|джаврис|джарис|jarvis|jarvice)"
_WAKE = re.compile(rf"^\s*(?:(?:эй|ой|окей|ok|hey)[\s,!.]*)?{_NAME}\w{{0,2}}[\s,!.:—-]*(.*)$", re.I | re.S)

_GREETING = re.compile(
    r"^\s*(?:я\s+дома|я\s+вернулся|я\s+пришёл|я\s+пришел|я\s+тут|привет\w*|здравствуй\w*|салом\w*|"
    r"доброе\s+утро|добрый\s+(?:день|вечер)|что\s+нового|как\s+дела|ну\s+что|доложи\w*)[\s,.!?]*$", re.I)


def find_wake(text: str) -> tuple[bool, str]:
    """(был ли зов, команда после имени). Пустая команда — просто позвали: ждать следующую фразу."""
    m = _WAKE.match(text or "")
    if not m:
        return False, ""
    return True, m.group(1).strip()


def is_greeting(text: str) -> bool:
    """«Я дома», «привет», «что нового» — не задача, а повод доложить обстановку."""
    return bool(_GREETING.match(text or ""))
