"""Разговор с JARVIS: что из сказанного — работа (задача), а что — просто разговор (ответ сразу).

Урок 2026-10-21: «ты здесь?», «Конец.», «не надо, номер 14» становились задачами с отчётом на минуту —
JARVIS выглядел новичком. Теперь задача — только то, где есть работа; вопрос — короткий ответ без
церемоний; остальное — мгновенно, без Claude.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

_END = r"[\s,.!?…]*"

STOP = re.compile(r"^\s*(?:не\s+надо|не\s+делай|стоп|отмена|отмени\w*|отставить|хватит|забудь)\b", re.I)
PRESENCE = re.compile(r"^\s*(?:ты\s+(?:здесь|тут|на\s+связи|меня\s+слышишь|слышишь(?:\s+меня)?)|алло|ау|"
                      r"проверка(?:\s+связи)?|ты\s+где)" + _END + "$", re.I)
THANKS = re.compile(r"^\s*(?:спасибо|благодарю|молодец|отлично|супер|класс|умница|красава)\w*" + _END +
                    r"(?:сэр|джарвис)?" + _END + "$", re.I)
REPEAT = re.compile(r"^\s*(?:повтори\w*|ещ[её]\s+раз|что\s+ты\s+сказал\w*|не\s+расслышал\w*)\b", re.I)
STATUS = re.compile(r"^\s*(?:что\s+(?:ты\s+)?(?:сейчас\s+)?делаешь|чем\s+(?:ты\s+)?(?:сейчас\s+)?занят|"
                    r"какие\s+(?:у\s+нас\s+|у\s+тебя\s+)?задачи|что\s+в\s+работе|что\s+(?:ты\s+)?(?:уже\s+)?сделал\w*|"
                    r"что\s+сделано|статус|отч[её]т)\b", re.I)
ABILITIES = re.compile(r"^\s*(?:что\s+(?:ты\s+)?(?:умеешь|можешь)|помощь|справка|как\s+тобой\s+пользоваться)\b", re.I)
NUMBER = re.compile(r"(?:номер|№|задач\w*)\s*(\d+)|\b(\d+)\b", re.I)

# повелительные глаголы работы: «сделай», «найди», «посчитай» … → задача исполнителю
WORK = re.compile(r"\b(?:сдела|созда|напиш|нарису|найд|открой|откро|провер|посчита|подготов|скача|установ|удал|"
                  r"отправ|запуст|настро|исправ|почин|собер|сохран|постав|добав|измен|обнов|покаж|сравн|распечата|"
                  r"напечата|отрендер|составь|придума|разбер|запиш|перенес|скопир|вычисл|проанализир|спланир|"
                  r"закаж|куп|напомн|позвон|ответь|можешь|сможешь|нужно|надо)\w*", re.I)
QUESTION_WORD = re.compile(r"^\s*(?:что|как|где|когда|почему|зачем|сколько|кто|какой|какая|какое|какие|каком|чей|"
                           r"можно\s+ли|есть\s+ли|правда\s+ли|ли)\b", re.I)


@dataclass(frozen=True)
class Intent:
    kind: str                     # presence|thanks|repeat|status|abilities|stop|noise|question|work
    number: str | None = None     # для stop: «номер 14»


def classify(text: str) -> Intent:
    t = (text or "").strip()
    if STOP.match(t):
        m = NUMBER.search(t)
        return Intent("stop", (m.group(1) or m.group(2)) if m else None)
    for kind, rx in (("presence", PRESENCE), ("thanks", THANKS), ("repeat", REPEAT),
                     ("status", STATUS), ("abilities", ABILITIES)):
        if rx.match(t):
            return Intent(kind)
    words = re.findall(r"[а-яёa-z]+", t.lower())
    if len(words) <= 1:
        return Intent("noise")
    asked = t.endswith("?") or bool(QUESTION_WORD.match(t))
    # «как настроить свет?» — вопрос (неопределённая форма); «настрой свет» — поручение
    orders = [w for w in WORK.findall(t) if not re.search(r"(?:ть|ти|ться|тись)$", w.lower())]
    if orders and not (asked and QUESTION_WORD.match(t) and not re.search(r"можешь|сможешь|нужно|надо", t, re.I)):
        return Intent("work")
    if asked:
        return Intent("question")
    return Intent("work")


